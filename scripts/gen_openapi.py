"""Regenerate openapi.yaml from the app. `uv run python scripts/gen_openapi.py` (add --check to verify only)."""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import yaml

from earshot_relay.api import openapi_document
from earshot_relay.config import load_settings
from earshot_relay.service import Relay
from earshot_relay.storage import S3Writer
from earshot_relay.store import Store

TARGET = Path(__file__).resolve().parent.parent / "openapi.yaml"
HEADER = "# Generated by scripts/gen_openapi.py from the FastAPI app. Do not edit by hand.\n"


def generate() -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        settings = load_settings({
            "EARSHOT_S3_ENDPOINT": "https://s3.example.com", "EARSHOT_BUCKET": "earshot", "EARSHOT_REGION": "us-east-1",
            "AWS_ACCESS_KEY_ID": "openapi-generator", "AWS_SECRET_ACCESS_KEY": "openapi-generator",
            "EARSHOT_RELAY_TOKEN": "x" * 40, "EARSHOT_RELAY_DATA_DIR": tmp,
        }, check_ffmpeg=False)
        store = Store(settings.db_path)
        try:
            return openapi_document(Relay(settings, store, S3Writer(settings)))
        finally:
            store.close()


def render(doc: dict) -> str:
    return HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)


if __name__ == "__main__":
    text = render(generate())
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.read_text() == text else 1)
    TARGET.write_text(text)
    print(f"wrote {TARGET}")
